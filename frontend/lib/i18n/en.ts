// Fallback per i tipi di issue non mappati: snake_case → "Snake case".
export function humanizeType(ty: string): string {
  const s = ty.replace(/_/g, " ").trim();
  return s ? s.charAt(0).toUpperCase() + s.slice(1) : ty;
}

